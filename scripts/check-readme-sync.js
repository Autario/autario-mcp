function escapePipes(s) {
    return String(s || '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function shortDesc(tool) {
    // First line, capped at 200 chars. Don't split on periods (breaks "e.g.", "(2010-2023)" etc.).
    const raw = (tool.description || '').split(/\n/)[0].trim();
    const trimmed = raw.length > 200 ? raw.slice(0, 197).trimEnd() + '...' : raw;
    return escapePipes(trimmed);
}

function paramList(tool) {
    const props = tool.inputSchema?.properties || {};
    const required = new Set(tool.inputSchema?.required || []);
    const items = Object.entries(props).map(([name, spec]) => {
        const tag = required.has(name) ? '**' + name + '**' : name;
        const type = spec.type || 'any';
        return `${tag} (${type})`;
    });
    return items.length ? items.join(', ') : '_none_';
}

// Derived from the tool's own `annotations`, never from a second list | the same
// object the Connectors Directory reads (spec 2026-09-22-mcp-tool-annotations).
function accessLabel(tool) {
    const a = tool.annotations || {};
    if (a.readOnlyHint === true) return 'read';
    if (a.destructiveHint === true) return 'write, destructive';
    return 'write';
}

function renderToolRow(tool) {
    return `| \`${tool.name}\` | ${accessLabel(tool)} | ${shortDesc(tool)} | ${paramList(tool)} |`;
}

function renderGroup(group, byName) {
    const lines = [];
    lines.push(`### ${group.title}`);
    lines.push('');
    lines.push(group.intro);
    lines.push('');
    lines.push('| Tool | Access | What it does | Parameters |');
    lines.push('| --- | --- | --- | --- |');
    for (const name of group.tools) {
        const tool = byName.get(name);
        if (!tool) continue;
        lines.push(renderToolRow(tool));
    }
    lines.push('');
    return lines.join('\n');
}

function generate() {
    const byName = new Map(TOOLS.map(t => [t.name, t]));
    const grouped = new Set(GROUPS.flatMap(g => g.tools));
    const ungrouped = TOOLS.filter(t => !grouped.has(t.name)).map(t => t.name);
    const missing = GROUPS.flatMap(g => g.tools).filter(name => !byName.has(name));

    const sections = GROUPS.map(g => renderGroup(g, byName)).join('\n');

    const total = TOOLS.length;
    const header = `<!-- generated by scripts/check-readme-sync.js | do not edit manually | run \`npm run build-readme\` after changing tools.js -->\n\n_${total} MCP tools, organized by function._\n\n`;

    return { body: header + sections, ungrouped, missing };
}

function readReadme() {
    return fs.readFileSync(README_PATH, 'utf8');
}

// Line endings are not drift. `core.autocrlf=true` (the default on the Windows
// dev boxes) checks this file out with CRLF, while the generator above emits
// LF, so a byte comparison reported the README as out of sync on EVERY Windows
// checkout no matter what tools.js said | and running --write "fixed" it by
// rewriting the section with LF, which git normalized straight back on commit.
// A permanently red gate is a gate nobody reads, so compare the CONTENT and
// let the file keep whatever endings the checkout gave it.
const normalizeEol = (s) => String(s).replace(/\r\n/g, '\n');

// Write back in the file's own dominant style, so regenerating the section
// never rewrites the untouched rest of the file as a side effect.
function writeReadme(content, original) {
    const crlf = (original.match(/\r\n/g) || []).length;
    const lf = (original.match(/\n/g) || []).length - crlf;
    const body = crlf > lf ? normalizeEol(content).replace(/\n/g, '\r\n') : content;
    fs.writeFileSync(README_PATH, body);
}

function spliceBetween(readme, startMarker, endMarker, body) {
    const startIdx = readme.indexOf(startMarker);
    const endIdx   = readme.indexOf(endMarker);
    if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
        throw new Error(`README is missing ${startMarker}/${endMarker} markers`);
    }
    const before = readme.slice(0, startIdx + startMarker.length);
    const after  = readme.slice(endIdx);
    return `${before}\n${body}\n${after}`;
}

function spliceSection(readme, body) {
    return spliceBetween(readme, START_MARKER, END_MARKER, body);
}

function spliceIntro(readme, body) {
    return spliceBetween(readme, INTRO_START, INTRO_END, body);
}

// Both generated sections applied to one README text: the one check the CLI,
// CI and the local Jest gate run.
function renderReadme(readme) {
    const { body } = generate();
    return spliceIntro(spliceSection(normalizeEol(readme), body), generateIntro());
}

function main() {
    const write = process.argv.includes('--write');
    const { body, ungrouped, missing } = generate();

    if (missing.length) {
        console.error(`ERROR: GROUPS reference tools not present in tools.js: ${missing.join(', ')}`);
        process.exit(2);
    }
    if (ungrouped.length) {
        console.error(`ERROR: tools.js exposes tools not assigned to any GROUP in this script: ${ungrouped.join(', ')}`);
        console.error('Add them to GROUPS in scripts/check-readme-sync.js, then re-run.');
        process.exit(2);
    }

    const readme = readReadme();
    const updated = renderReadme(readme);
    const inSync = normalizeEol(updated) === normalizeEol(readme);

    if (write) {
        if (inSync) {
            console.log('README is already in sync. No changes written.');
            return;
        }
        writeReadme(updated, readme);
        console.log(`README regenerated (${TOOLS.length} tools, ${GROUPS.length} groups).`);
        return;
    }

    if (!inSync) {
        console.error('ERROR: a generated README section (intro or Tool Reference) is out of sync with entityDescription.json / tools.js.');
        console.error('Fix: run `npm run build-readme --prefix backend/mcp` and commit the change.');
        process.exit(1);
    }
    console.log(`README is in sync (${TOOLS.length} tools).`);
}

